    public static IReadOnlyList<NativeField> Fields { get; } = Channels.Values.Select(c => c.Field).Concat(SimulatorRace.Fields).ToArray();
    private static IEnumerable<Channel> Build()
    {
        string[] corners = ["左前","右前","左后","右后"];
        foreach (var m in Members)
        {
            bool vehicle = m.Section is Section.Physics or Section.Wheel or Section.Timing;
            foreach (var grid in vehicle ? new[] { false, true } : new[] { false })
            for (int i=0; i < (m.Section == Section.Wheel ? 4 : 1); i++)
            {
                var group = m.Section switch { Section.Timing => "计时", Section.Session or Section.Results => "赛事", Section.Header => "接口", _ => "物理" };
                var scope = vehicle ? grid ? "全场" : "本车" : "";
                var wheel = m.Section == Section.Wheel ? corners[i] : "";
                var key = $"LMU.{(grid ? "Grid." : "")}{m.Section}.{m.Name}" + (wheel.Length > 0 ? "." + Metrics.Wheels[i] : "");
                yield return new(new(key, scope + group + wheel + m.Title, scope + group), m, i, grid);
            }
        }
    }
